import { readFile, writeFile } from "node:fs/promises";

const matrixUrl = new URL("../../support-matrix.json", import.meta.url);
const pluginUrl = new URL("../../addons/godot_mini_game/plugin.cfg", import.meta.url);
const engineTemplateUrl = new URL("../../addons/godot_mini_game/engine/template.json", import.meta.url);
const outputUrl = new URL("../app/site-data.generated.ts", import.meta.url);

const matrix = JSON.parse(await readFile(matrixUrl, "utf8"));
const pluginCfg = await readFile(pluginUrl, "utf8");
const engineTemplate = JSON.parse(await readFile(engineTemplateUrl, "utf8"));
const pluginVersion = pluginCfg.match(/^version="([^"]+)"$/m)?.[1];

if (!pluginVersion || pluginVersion !== matrix.pluginVersion) {
  throw new Error("plugin.cfg and support-matrix.json versions must match");
}
if (!Number.isInteger(matrix.bridgeAbi) || matrix.bridgeAbi < 1) {
  throw new Error("support-matrix.json must declare a positive Bridge ABI");
}
if (!Array.isArray(matrix.certified) || matrix.certified.length === 0) {
  throw new Error("support-matrix.json must declare at least one certified engine tuple");
}
if (!Number.isInteger(matrix.templateSchema) || matrix.templateSchema < 1) {
  throw new Error("support-matrix.json must declare a positive template schema");
}
if (!Number.isInteger(matrix.outputManifestSchema) || matrix.outputManifestSchema < 1) {
  throw new Error("support-matrix.json must declare a positive output manifest schema");
}
const tiktokContract = matrix.platformContracts?.tiktok;
if (
  tiktokContract?.runtimeType !== "native"
  || tiktokContract?.supportTier !== "beta"
  || tiktokContract?.apiNamespace !== "TTMinis.game"
  || tiktokContract?.minimumClientVersion !== "43.4.0"
  || tiktokContract?.subpackageField !== "subpackages"
  || tiktokContract?.devtool !== "ttmg"
  || tiktokContract?.validation?.devtoolCompile !== "required"
  || tiktokContract?.validation?.realDevice !== "required-for-release"
) {
  throw new Error("support-matrix.json must declare the TikTok contract, Native runtime, beta tier, and validation gates");
}

const bundledRows = matrix.certified.filter((target) => target.template?.source === "bundled");
if (bundledRows.length !== 1) {
  throw new Error("support-matrix.json must declare exactly one bundled template row");
}
const bundled = bundledRows[0];
if (
  bundled.godotVersion !== engineTemplate.godot?.version
  || bundled.godotCommit !== engineTemplate.godot?.commit
  || bundled.emscriptenVersion !== engineTemplate.emscriptenVersion
  || bundled.profile !== engineTemplate.profile
  || bundled.target !== engineTemplate.target
  || bundled.templateRevision !== engineTemplate.revision
  || matrix.bridgeAbi !== engineTemplate.bridgeAbi
  || matrix.templateSchema !== engineTemplate.schema
) {
  throw new Error("bundled certification and engine/template.json identities must match");
}

const releaseData = {
  pluginVersion,
  bridgeAbi: matrix.bridgeAbi,
  templateSchema: matrix.templateSchema,
  outputManifestSchema: matrix.outputManifestSchema,
  platformContracts: matrix.platformContracts,
  bundled,
  certified: matrix.certified,
};

await writeFile(
  outputUrl,
  `// Generated by scripts/generate-site-data.mjs. Do not edit by hand.\n` +
    `export const releaseData = ${JSON.stringify(releaseData, null, 2)} as const;\n`,
  "utf8",
);

console.log(
  `Generated website release data for v${pluginVersion}, Bridge ABI ${matrix.bridgeAbi}.`,
);
